DROP TRIGGER IF EXISTS fernsvilla_admin_audit ON public.community_issues;
CREATE TRIGGER fernsvilla_admin_audit AFTER INSERT OR UPDATE OR DELETE
 ON public.community_issues FOR EACH ROW
 EXECUTE FUNCTION public.fernsvilla_audit_change();
COMMIT;
