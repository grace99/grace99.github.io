-- Apply after 016. Also supports the community_issues table already created manually.
-- Preserves the legacy JSON array and imports each legacy issue only once.
BEGIN;

CREATE TABLE IF NOT EXISTS public.community_issues (
 issue_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 issue_title text NOT NULL CHECK(length(btrim(issue_title)) BETWEEN 1 AND 250),
 issue_description text NOT NULL CHECK(length(btrim(issue_description))>0),
 issue_category text NOT NULL DEFAULT 'Maintenance' CHECK(issue_category IN ('Maintenance','Security','Water','Electrical','Roads & drainage','Waste management','Landscaping','Common facilities','Other')),
 issue_severity text NOT NULL DEFAULT 'Medium' CHECK(issue_severity IN ('Low','Medium','High','Critical')),
 recurring_issue boolean NOT NULL DEFAULT false,
 villa text REFERENCES public."villaMaster"("Villa"), issue_location text,
 reported_by uuid DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE SET NULL,
 reported_by_name text, reported_on timestamptz NOT NULL DEFAULT now(),
 assigned_to uuid REFERENCES auth.users(id) ON DELETE SET NULL,
 target_resolution_date date,
 issue_status text NOT NULL DEFAULT 'Open' CHECK(issue_status IN ('Open','Acknowledged','In progress','On hold','Resolved','Closed','Cancelled')),
 resolution_description text, resolution_date timestamptz,
 resolved_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 CHECK(issue_status NOT IN ('Resolved','Closed') OR (resolution_date IS NOT NULL AND nullif(btrim(resolution_description),'') IS NOT NULL)),
 CHECK(resolution_date IS NULL OR resolution_date>=reported_on)
);
CREATE INDEX IF NOT EXISTS community_issues_status_reported_idx ON public.community_issues(issue_status,reported_on DESC);
CREATE INDEX IF NOT EXISTS community_issues_villa_idx ON public.community_issues(villa);
CREATE INDEX IF NOT EXISTS community_issues_reporter_idx ON public.community_issues(reported_by);
CREATE INDEX IF NOT EXISTS community_issues_assignee_idx ON public.community_issues(assigned_to);
ALTER TABLE public.community_issues ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.community_issues FROM anon,authenticated;
GRANT SELECT,INSERT,UPDATE,DELETE ON public.community_issues TO authenticated;
GRANT USAGE ON SEQUENCE public.community_issues_issue_id_seq TO authenticated;
DROP POLICY IF EXISTS community_issues_member_read ON public.community_issues;
CREATE POLICY community_issues_member_read ON public.community_issues FOR SELECT TO authenticated
 USING(EXISTS(SELECT 1 FROM public.fernsvilla_members m WHERE m.user_id=auth.uid()));
DROP POLICY IF EXISTS community_issues_manager_write ON public.community_issues;
CREATE POLICY community_issues_manager_write ON public.community_issues FOR ALL TO authenticated
 USING(EXISTS(SELECT 1 FROM public.fernsvilla_members m WHERE m.user_id=auth.uid() AND m.role IN ('admin','editor')))
 WITH CHECK(EXISTS(SELECT 1 FROM public.fernsvilla_members m WHERE m.user_id=auth.uid() AND m.role IN ('admin','editor')));

ALTER TABLE public.community_issues ADD COLUMN IF NOT EXISTS legacy_issue_id text;
CREATE UNIQUE INDEX IF NOT EXISTS community_issues_legacy_id_key
 ON public.community_issues(legacy_issue_id);

CREATE OR REPLACE FUNCTION public.fernsvilla_issue_updated_at()
RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $function$
BEGIN
 IF TG_OP='UPDATE' THEN
  NEW.created_at:=OLD.created_at;
  NEW.reported_by:=OLD.reported_by;
 END IF;
 NEW.updated_at:=now();
 IF NEW.issue_status IN ('Resolved','Closed') THEN
  IF TG_OP='INSERT' THEN
   NEW.resolved_by:=auth.uid();
  ELSIF OLD.issue_status NOT IN ('Resolved','Closed') THEN
   NEW.resolved_by:=auth.uid();
  ELSE
   NEW.resolved_by:=OLD.resolved_by;
  END IF;
 ELSE
  NEW.resolved_by:=NULL;
  NEW.resolution_date:=NULL;
 END IF;
 RETURN NEW;
END;
$function$;
DROP TRIGGER IF EXISTS fernsvilla_issue_updated_at ON public.community_issues;
CREATE TRIGGER fernsvilla_issue_updated_at BEFORE INSERT OR UPDATE
 ON public.community_issues FOR EACH ROW
 EXECUTE FUNCTION public.fernsvilla_issue_updated_at();

INSERT INTO public.community_issues (
 legacy_issue_id,issue_title,issue_description,issue_category,
 issue_location,issue_status,resolution_description,resolution_date
)
SELECT coalesce(item->>'id','position-'||ordinality::text),
 left(coalesce(nullif(btrim(item->>'title'),''),'Imported community issue'),250),
 coalesce(nullif(btrim(item->>'detail'),''),'Imported from legacy community issues.'),
 CASE WHEN item->>'category' IN ('Maintenance','Security','Water','Electrical',
 'Roads & drainage','Waste management','Landscaping','Common facilities','Other')
 THEN item->>'category' ELSE 'Other' END,
 item->>'villa',
 CASE WHEN item->>'status' IN ('Open','Acknowledged','In progress','On hold','Resolved','Closed','Cancelled')
 THEN item->>'status' ELSE 'Open' END,
 CASE WHEN item->>'status' IN ('Resolved','Closed')
 THEN 'Imported as resolved from legacy records; original resolution details and date were not recorded.' END,
 CASE WHEN item->>'status' IN ('Resolved','Closed') THEN now() END
FROM public.fernsvilla_state s,
 LATERAL jsonb_array_elements(coalesce(s.data->'issues','[]'::jsonb)) WITH ORDINALITY AS legacy(item,ordinality)
WHERE s.id=1
ON CONFLICT (legacy_issue_id) DO NOTHING;

